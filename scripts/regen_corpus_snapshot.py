#!/usr/bin/env python
"""Regenerate the full blueprint snapshot from the MCP's canon YAML.

A DEV-ONLY tool, the blueprint sibling of ``regen_catalog_fixture.py``: it copies every
``app/corpus/data/blueprints/bp-*.yaml`` in the sibling ``clickhouse-api`` (MCP) repo,
sorted by filename and parsed verbatim, into
``tests/fixtures/corpus_snapshot/blueprints.yaml``. The header records the canon's
``BLUEPRINTS_SHA`` so the drift guard can name the exact corpus the snapshot mirrors.

It refuses an UNSEALED canon — YAML edited without regenerating ``MANIFEST.sha256`` /
``BLUEPRINTS_SHA`` (``tools/check_corpus_parity.py --write`` in the MCP repo) — because
the recorded fingerprint would then describe a different corpus than the one copied.

Usage
-----
    python scripts/regen_corpus_snapshot.py

Locating the MCP repo (first match wins):
    1. ``$CLICKHOUSE_API_REPO`` env var (absolute path to the clickhouse-api repo)
    2. sibling of this agent repo: ``../clickhouse-api``

Commit the result. Every canon blueprint carries a reviewed ``presentation``;
``scripts/audit_blueprint_presentations.py`` checks each against the document
materializer and fails for a blueprint that has none.
"""

from __future__ import annotations

import datetime as dt
import hashlib
import os
from pathlib import Path

import yaml

# This file lives at <agent-repo>/scripts/regen_corpus_snapshot.py
_AGENT_REPO = Path(__file__).resolve().parent.parent
_DEFAULT_MCP_REPO = _AGENT_REPO.parent / "clickhouse-api"
_SNAPSHOT = _AGENT_REPO / "tests" / "fixtures" / "corpus_snapshot" / "blueprints.yaml"
_CANON = Path("app") / "corpus" / "data" / "blueprints"


def _resolve_canon() -> Path:
    env = os.environ.get("CLICKHOUSE_API_REPO")
    canon = (Path(env).expanduser() if env else _DEFAULT_MCP_REPO) / _CANON
    if not canon.is_dir():
        raise SystemExit(
            "ERROR: cannot locate the clickhouse-api (MCP) blueprint canon.\n"
            f"  Looked for: {canon}\n"
            "  Set CLICKHOUSE_API_REPO to the repo path, or clone it as a sibling\n"
            "  directory of this agent repo."
        )
    return canon


def _sealed_fingerprint(canon: Path) -> str:
    """Return BLUEPRINTS_SHA after proving the YAML matches MANIFEST.sha256 and the sidecar."""
    manifest = (canon / "MANIFEST.sha256").read_text(encoding="utf-8")
    recorded = {name: sha for sha, name in (line.split("  ", 1) for line in manifest.splitlines() if line)}
    live = {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(canon.glob("*.yaml"))}
    sidecar = (canon / "BLUEPRINTS_SHA").read_text(encoding="utf-8").strip()
    if live != recorded or hashlib.sha1(manifest.encode("utf-8")).hexdigest() != sidecar:
        changed = sorted(set(live.items()) ^ set(recorded.items()))
        raise SystemExit(
            "ERROR: the MCP canon is unsealed (YAML differs from MANIFEST.sha256 or\n"
            "  BLUEPRINTS_SHA). Run `python tools/check_corpus_parity.py --write` in the\n"
            f"  clickhouse-api repo first. Differing entries: {[name for name, _ in changed][:10]}"
        )
    return sidecar


def render(canon: Path, *, today: dt.date) -> str:
    docs = [yaml.safe_load(p.read_text(encoding="utf-8")) for p in sorted(canon.glob("bp-*.yaml"))]
    header = (
        f"# Full clickhouse-api blueprint snapshot, synchronized {today.isoformat()} "
        f"({len(docs)} blueprints).\n"
        f"# BLUEPRINTS_SHA: {_sealed_fingerprint(canon)}\n"
        "# Source: app/corpus/data/blueprints/bp-*.yaml, sorted by filename.\n"
        "# Generated by scripts/regen_corpus_snapshot.py; do not hand-edit.\n"
        "# Used for full-corpus parity and SQL round-trip tests, not the local demo warehouse seed.\n"
    )
    return header + yaml.safe_dump(docs, sort_keys=False, allow_unicode=True, width=100)


def main() -> None:
    canon = _resolve_canon()
    _SNAPSHOT.write_text(render(canon, today=dt.date.today()), encoding="utf-8")
    print(f"Wrote {_SNAPSHOT.relative_to(_AGENT_REPO)} from {canon}")


if __name__ == "__main__":
    main()
